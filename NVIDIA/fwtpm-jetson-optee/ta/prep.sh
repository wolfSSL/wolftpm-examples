#!/bin/bash
# Symlink the wolfCrypt, fwTPM and OP-TEE port sources into the TA tree, and
# the three include roots alongside them.
#
# The OP-TEE TA build resolves every srcs-y and global-incdirs-y entry against
# the sub.mk directory, so nothing outside it can be named directly. Symlinks
# keep one copy of the truth and let the wolfSSL and wolfTPM trees live
# anywhere. An earlier version of this port copied the sources instead, and a
# stale copy once made a failed build look like a successful one.
#
#   WOLFSSL=<path> WOLFTPM=<path> ./prep.sh
set -eu

here="$(cd "$(dirname "$0")" && pwd)"
port="$(cd "$here/.." && pwd)"

WOLFSSL="${WOLFSSL:-$port/../../../wolfssl}"
WOLFTPM="${WOLFTPM:-$port/../../../wolftpm}"
wolfssl="$(cd "$WOLFSSL" && pwd)"
wolftpm="$(cd "$WOLFTPM" && pwd)"

test -f "$wolfssl/wolfcrypt/src/wc_port.c" || {
    echo "not a wolfSSL tree: $wolfssl" >&2; exit 1; }
# A configured wolfSSL tree has a generated config.h at its root, and this
# build puts that root on the include path, so it shadows the OP-TEE devkit's
# own <config.h>. The failure lands inside the devkit's user_ta_header.c and
# looks nothing like its cause, so refuse it here instead.
test -f "$wolfssl/config.h" && {
    echo "$wolfssl has a generated config.h and would shadow the OP-TEE" >&2
    echo "devkit's <config.h>. Use an unconfigured wolfSSL source tree, or" >&2
    echo "run 'make distclean' in that one first." >&2
    exit 1; }

test -d "$wolftpm/src/fwtpm/ports/optee" || {
    echo "wolfTPM tree has no OP-TEE port: $wolftpm" >&2
    echo "needs the WOLFTPM_OPTEE support in wolfTPM v4.2.0 or later" >&2
    exit 1; }

# Pull the two lists out of the shared srcs.mk rather than restating them.
wc_srcs=$(grep -E '^[[:space:]]+wolfcrypt/src/([a-z0-9_/-]+/)?[a-z0-9_-]+\.c' \
    "$port/srcs.mk" | tr -d ' \t\\')
fwtpm_srcs=$(grep -E '^[[:space:]]+src/[a-z0-9_/]+\.c' "$port/srcs.mk" \
    | tr -d ' \t\\')

rm -rf "$here/wc" "$here/wt" "$here/port"
rm -f "$here/inc-cfg" "$here/inc-wolfssl" "$here/inc-wolftpm"
mkdir -p "$here/wc" "$here/wt" "$here/port"

for s in $wc_srcs; do
    test -f "$wolfssl/$s" || { echo "missing $wolfssl/$s" >&2; exit 1; }
    ln -s "$wolfssl/$s" "$here/wc/$(basename "$s")"
done
for s in $fwtpm_srcs; do
    test -f "$wolftpm/$s" || { echo "missing $wolftpm/$s" >&2; exit 1; }
    ln -s "$wolftpm/$s" "$here/wt/$(basename "$s")"
done
# Only the sources: the shared command-ID header is reached through the
# wolfTPM include path as <wolftpm/fwtpm/fwtpm_optee.h>.
for s in "$wolftpm"/src/fwtpm/ports/optee/*.c; do
    ln -s "$s" "$here/port/$(basename "$s")"
done

# Include roots. inc-cfg holds user_settings.h.
ln -s "$port" "$here/inc-cfg"
ln -s "$wolfssl" "$here/inc-wolfssl"
ln -s "$wolftpm" "$here/inc-wolftpm"

# The trusted application's UUID has one definition, in wolfTPM, and both the
# signed binary's filename and TA_UUID are derived from it here. See the note
# on WOLFTPM_OPTEE_TA_UUID_STR in wolftpm/fwtpm/fwtpm_optee.h for why the same
# value has to appear in three separately built places.
uuid=$(sed -n 's/^#define WOLFTPM_OPTEE_TA_UUID_STR  *"\(.*\)"$/\1/p' \
    "$wolftpm/wolftpm/fwtpm/fwtpm_optee.h")
case "$uuid" in
    [0-9a-f]???????-????-????-????-???????????? ) ;;
    *) echo "could not read WOLFTPM_OPTEE_TA_UUID_STR from $wolftpm" >&2
       exit 1 ;;
esac

printf 'TA_UUID_STR = %s\n' "$uuid" > "$here/uuid.mk"
python3 -I -c '
import sys
u = sys.argv[1].replace("-", "")
b = [u[i:i+2] for i in range(0, 32, 2)]
print("/* Generated by prep.sh from WOLFTPM_OPTEE_TA_UUID_STR. Do not edit. */")
print("#define TA_UUID \\")
print("    { 0x%s, 0x%s, 0x%s, \\" % (u[0:8], u[8:12], u[12:16]))
print("      { " + ", ".join("0x" + x for x in b[8:]) + " } }")
' "$uuid" > "$here/uuid_macro.inc"
echo "UUID:    $uuid (from wolfTPM)"

echo "wolfSSL: $wolfssl"
echo "wolfTPM: $wolftpm"
echo "wc: $(ls "$here/wc" | wc -l) wolfCrypt sources"
echo "wt: $(ls "$here/wt" | wc -l) fwTPM sources"
echo "port: $(ls "$here/port" | wc -l) OP-TEE port sources"
